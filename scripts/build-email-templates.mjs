function banner(lines) {
  return `<!--\n${lines.map((l) => `  ${l}`).join('\n')}\n-->\n`;
}

const GENERATED = 'GENERATED by scripts/build-email-templates.mjs — do not edit by hand.';

export function buildFiles() {
  const files = {};
  const enrollmentPlaceholders = { firstName: '{{FIRST_NAME}}', courseEntryUrl: '{{COURSE_ENTRY_URL}}' };

  files['custom-resend/enrollment-confirmation.html'] = banner([
    'AIMT — Paid enrollment confirmation (custom Resend send).',
    GENERATED,
    'Source of truth: renderEnrollmentHtml() in functions/_lib/enrollment/paid-enrollment-email.mjs.',
    'Sent by functions/api/stripe-webhook.js after the entitlement write. LIVE.',
    `Subject: ${ENROLLMENT_SUBJECT}`,
    '{{FIRST_NAME}}: first word of the Stripe customer name. With no name the',
    '  headline renders "Welcome to AIMT." (never a placeholder name).',
    '{{COURSE_ENTRY_URL}}: https://aimtrichology.com/success.html?session_id=<id>',
    '  (the paid-session account-setup link).',
    'Plain-text part: enrollment-confirmation.txt. Not the Stripe receipt.',
  ]) + renderEnrollmentHtml(enrollmentPlaceholders) + '\n';
  files['custom-resend/enrollment-confirmation.txt'] = renderEnrollmentText(enrollmentPlaceholders) + '\n';

  files['custom-resend/invite-manual-grant.html'] = banner([
    'AIMT — Manual-grant student invite (custom Resend send).',
    GENERATED,
    'Source of truth: renderInviteHtml() in functions/_lib/admin/manual-grant-invite-email.mjs.',
    'Sent by grantAccess() in functions/api/admin/index.js when a grant creates a new account. LIVE.',
    `Subject: ${INVITE_SUBJECT}`,
    '{{FIRST_NAME}}: from the grant form. With no name: "Welcome to AIMT."',
    'CTA: https://aimtrichology.com/student-access (canonical, fixed).',
    'Plain-text part: invite-manual-grant.txt.',
  ]) + renderInviteHtml({ firstName: '{{FIRST_NAME}}' }) + '\n';
  files['custom-resend/invite-manual-grant.txt'] = renderInviteText({ firstName: '{{FIRST_NAME}}' }) + '\n';

  for (const [name, t] of Object.entries(SUPABASE_TEMPLATES)) {
    files[`supabase-auth/${name}.html`] = banner([
      `AIMT — Supabase Auth "${t.slot}" template.`,
      GENERATED,
      `Paste into: Supabase Dashboard → Authentication → Email Templates → ${t.slot}`,
      `Subject: ${t.subject}`,
      `Supabase variables used (do not rename): ${t.variables.join(', ')}`,
      'Changing this file does NOT change the live email until it is pasted.',
    ]) + t.html() + '\n';
  }
  return files;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [rel, content] of Object.entries(buildFiles())) {
    const file = path.join(DIR, rel);
    let current = null;
    try { current = readFileSync(file, 'utf8'); } catch {}
    if (current === content) continue;
    if (check) { stale++; console.error(`stale: docs/email-templates/${rel}`); continue; }
    writeFileSync(file, content);
    console.log(`wrote docs/email-templates/${rel}`);
  }
  if (check && stale) process.exit(1);
}
