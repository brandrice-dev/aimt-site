// Generates docs/email-templates/ from the production email renderers.
//
//   node scripts/build-email-templates.mjs          write the files
//   node scripts/build-email-templates.mjs --check  exit 1 if any file is stale
//
// Custom Resend sends (enrollment, manual-grant invite): rendered by the
// exact functions production calls, with {{PLACEHOLDER}} markers in place
// of per-recipient values, so the docs copies can never drift from what
// is actually sent. Supabase Auth templates: built from the same shared
// shell (functions/_lib/email/aimt-email-shell.mjs) with Supabase's Go
// template variables ({{ .ConfirmationURL }}, {{ .NewEmail }}) written
// literally — those files are pasted into the Supabase Dashboard by the
// owner; changing them here does not change the live emails.
//
// Dev-time tool only (not a deploy build step); zero dependencies.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { renderEnrollmentHtml, renderEnrollmentText, ENROLLMENT_SUBJECT } from '../functions/_lib/enrollment/paid-enrollment-email.mjs';
import { renderInviteHtml, renderInviteText, INVITE_SUBJECT } from '../functions/_lib/admin/manual-grant-invite-email.mjs';
import {
  renderEmail, paragraph, button, row, link, SUPPORT_LINK, COLORS, FONT_BODY,
} from '../functions/_lib/email/aimt-email-shell.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIR = path.join(ROOT, 'docs/email-templates');

const CONFIRMATION_URL = '{{ .ConfirmationURL }}';

function rawLink(url) {
  return row(
    `<p style="margin:0; font-family:${FONT_BODY}; font-size:13px; line-height:1.6; color:${COLORS.body}; word-break:break-all;">${link(url, url)}</p>`,
    { top: 6 }
  );
}

