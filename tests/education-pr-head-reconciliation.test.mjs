import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { buildPublicationManifest, computePreparedArtifactDigest } from '../functions/_lib/education-ops/education-publication-state.mjs';
import { verifyPrHeadReconciliation, reconcileScalpPrHead, SCALP_PR } from '../scripts/_lib/education-pr-head-reconciliation.mjs';
import { SCALP_HANDOFF } from '../scripts/_lib/education-exact-candidate.mjs';

// Candidate integrity itself is covered by education-candidate-bundle tests;
// this suite isolates the extra merge proof and compare-before-write boundary.
const integrity = { verifyIntegrityFn: async () => ({ valid: true }) };
async function fixture() {
  const bundle = { topic_slug: SCALP_HANDOFF.topic, route: '/education/scalp-health/scalp-microbiome',
    cluster: 'scalp-health', originating_run_id: 'original', generation_source_hash: SCALP_HANDOFF.generation_source_hash,
    prepared_artifact: { original: 'approved bytes' } };
  const manifest = buildPublicationManifest({ runId: 'publish', topicSlug: bundle.topic_slug, route: bundle.route,
    cluster: bundle.cluster, generationSourceHash: bundle.generation_source_hash,
    preparedArtifactDigest: await computePreparedArtifactDigest(bundle.prepared_artifact), candidateOriginatingRunId: bundle.originating_run_id });
  manifest.state = 'PR_OPEN';
  manifest.generated = { pr_number: 77, pr_url: 'https://github.com/brandrice-dev/aimt-site/pull/77', branch: SCALP_PR.branch,
    expected_head_sha: SCALP_PR.head, article_path: SCALP_PR.files[0], plan_artifact_path: SCALP_PR.files[1], hub_path: SCALP_PR.files[2], sitemap_path: SCALP_PR.files[3] };
  const main = 'a'.repeat(40), head = 'b'.repeat(40);
  const proof = { mainSha: main, releaseHead: main, checkoutHead: main, newHead: head, parents: [SCALP_PR.head, main],
    pr: { number: 77, html_url: manifest.generated.pr_url, state: 'open', merged: false, draft: false,
      head: { sha: head, ref: SCALP_PR.branch, repo: { full_name: 'brandrice-dev/aimt-site' } },
      base: { ref: 'main', repo: { full_name: 'brandrice-dev/aimt-site' } } },
    diffPaths: [...SCALP_PR.files], originalDiffPaths: [...SCALP_PR.files],
    originalFiles: Object.fromEntries(SCALP_PR.files.map((f) => [f, 'exact '+f])),
    newFiles: Object.fromEntries(SCALP_PR.files.map((f) => [f, 'exact '+f])) };
  return { manifest, bundle, proof };
}
test('only unchanged four-file publication with exact original-head/main merge is reconcilable', async () => {
  const f = await fixture();
  const audit = await verifyPrHeadReconciliation(f.manifest, f.bundle, f.proof, integrity);
  assert.equal(audit.old_head_sha, SCALP_PR.head);
  assert.equal(audit.main_sha, f.proof.mainSha);
  assert.equal(Object.keys(audit.file_sha256).length, 4);
  assert.equal(f.manifest.generated.expected_head_sha, SCALP_PR.head);
});
test('reconciliation rejects wrong state, identity, candidate, parentage, extra files and any generated byte change', async () => {
  const mutations = [
    (f) => { f.manifest.state = 'PUBLISHED'; }, (f) => { f.manifest.merge.merged = true; },
    (f) => { f.manifest.clearance.persisted = true; }, (f) => { f.manifest.db_publish.attempted = true; },
    (f) => { f.manifest.deployment.state = 'success'; }, (f) => { f.manifest.generated.pr_number = 78; },
    (f) => { f.manifest.generated.expected_head_sha = 'c'.repeat(40); }, (f) => { f.proof.pr.state = 'closed'; },
    (f) => { f.proof.pr.merged = true; }, (f) => { f.proof.pr.head.repo.full_name = 'other/repo'; },
    (f) => { f.proof.pr.base.ref = 'other'; }, (f) => { f.proof.pr.head.ref = 'other'; },
    (f) => { f.bundle.generation_source_hash = 'c'.repeat(64); }, (f) => { f.bundle.originating_run_id = 'other'; },
    (f) => { f.bundle.prepared_artifact.original = 'changed'; }, (f) => { f.proof.mainSha = 'c'.repeat(40); },
    (f) => { f.proof.checkoutHead = 'c'.repeat(40); }, (f) => { f.proof.newHead = 'c'.repeat(40); },
    (f) => { f.proof.parents.reverse(); }, (f) => { f.proof.parents.push('c'.repeat(40)); },
    (f) => { f.proof.diffPaths.push('tests/changed.mjs'); }, (f) => { f.proof.originalDiffPaths.pop(); },
    ...SCALP_PR.files.map((file) => (f) => { f.proof.newFiles[file] += '\n'; }),
  ];
  for (const mutate of mutations) {
    const f = await fixture(); mutate(f);
    await assert.rejects(verifyPrHeadReconciliation(f.manifest, f.bundle, f.proof, integrity));
  }
  const f = await fixture();
  await assert.rejects(verifyPrHeadReconciliation(f.manifest, f.bundle, f.proof, { verifyIntegrityFn: async () => ({ valid: false }) }));
});
test('durable transition rechecks manifest, latest artifact, PR and main before writing and preserves history', async () => {
  // Real integrity validator uses the approved bundle in production; isolate it
  // here by injecting the proof verifier, never by allowing a CLI bypass.
  for (const changed of ['none', 'manifest', 'artifact', 'head', 'main', 'merged']) {
    const f = await fixture(); f.manifest.head_reconciliations = [{ prior: 'retained' }];
    const bytes = Buffer.from(JSON.stringify(f.manifest)); let reads = 0, prReads = 0, writes = 0;
    const env = { PUBLICATION_OPERATION: 'publish', APPROVE_PUBLICATION: 'true', GITHUB_EVENT_NAME: 'workflow_dispatch',
      GITHUB_REF: 'refs/heads/main', GITHUB_REPOSITORY: 'brandrice-dev/aimt-site',
      GITHUB_SHA: f.proof.mainSha, RELEASE_HEAD: f.proof.mainSha, PUBLICATION_STATE_ARTIFACT_ID: '123', GITHUB_RUN_ID: '456' };
    const io = {
      readManifest: () => ++reads === 2 && changed === 'manifest' ? Buffer.from('{}') : bytes,
      readPr: () => ++prReads === 1 ? f.proof.pr : { ...f.proof.pr, merged: changed === 'merged',
        head: { ...f.proof.pr.head, sha: changed === 'head' ? 'c'.repeat(40) : f.proof.newHead } },
      readProof: () => f.proof, verifyProof: (m, b, p) => verifyPrHeadReconciliation(m, b, p, integrity),
      readMain: () => changed === 'main' ? 'c'.repeat(40) : env.RELEASE_HEAD,
      readLatestArtifact: () => changed === 'artifact' ? 124 : 123,
      persist: (next) => { writes++; assert.deepEqual(next.head_reconciliations[0], { prior: 'retained' });
        assert.equal(next.head_reconciliations[1].source_publication_artifact_id, '123');
        assert.equal(next.generated.expected_head_sha, f.proof.newHead);
        assert.deepEqual(next.merge, f.manifest.merge); assert.deepEqual(next.db_publish, f.manifest.db_publish); },
    };
    if (changed === 'none') assert.equal((await reconcileScalpPrHead('unused', env, f.bundle, io)).reconciled, true);
    else await assert.rejects(reconcileScalpPrHead('unused', env, f.bundle, io), /STALE_OR_CONCURRENT/);
    assert.equal(writes, changed === 'none' ? 1 : 0);
  }
});
